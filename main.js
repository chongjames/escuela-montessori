  var lang = "es";
  try {
    if (localStorage.getItem("kaalam-lang") === "en") lang = "en";
  } catch (e) {}

  function apply(next) {
    lang = next === "en" ? "en" : "es";
    var pack = STR[lang];
    document.documentElement.lang = lang === "en" ? "en" : "es-MX";
    document.querySelectorAll("[data-i18n]").forEach(function (node) {
      var key = node.getAttribute("data-i18n");
      if (pack[key] != null) node.textContent = pack[key];
    });
    document.querySelectorAll(".js-lang").forEach(function (btn) {
      btn.textContent = lang === "en" ? "ES" : "EN";
      btn.setAttribute("aria-pressed", lang === "en" ? "true" : "false");
    });
    var menuBtn = document.getElementById("menu-btn");
    if (menuBtn && menuBtn.getAttribute("aria-expanded") !== "true") {
      menuBtn.textContent = pack.menu;
    }
    document.title = pack.title;
    var og = document.querySelector('meta[property="og:title"]');
    if (og) og.setAttribute("content", pack.title);
    try { localStorage.setItem("kaalam-lang", lang); } catch (e) {}
    renderHomeNotes();
    if (typeof window.kaalamAfterLang === "function") window.kaalamAfterLang(lang);
  }

  function renderHomeNotes() {
    var box = document.getElementById("notes-home");
    if (!box) return;
    box.textContent = "";
    var posts = (window.POSTS || []).slice().sort(function (a, b) {
      return a.date < b.date ? 1 : -1;
    });
    if (!posts.length) {
      var empty = document.createElement("p");
      empty.className = "prose";
      empty.textContent = STR[lang].notesEmpty;
      box.appendChild(empty);
      return;
    }
    var post = posts[0];
    var link = document.createElement("a");
    link.className = "note-link";
    link.href = "blog.html#" + post.id;
    var title = document.createElement("span");
    title.className = "note-link__title";
    title.textContent = post.title[lang] || post.title.es;
    var when = document.createElement("span");
    when.className = "note-link__date";
    when.textContent = formatNoteDate(post.date);
    link.appendChild(when);
    link.appendChild(title);
    box.appendChild(link);
  }

  function formatNoteDate(iso) {
    var parts = String(iso).split("-");
    var d = new Date(Number(parts[0]), Number(parts[1]) - 1, Number(parts[2]));
    return d.toLocaleDateString(lang === "en" ? "en-GB" : "es-MX", {
      day: "numeric",
      month: "long",
      year: "numeric",
    });
  }

  apply(lang);

  document.querySelectorAll(".js-lang").forEach(function (btn) {
    btn.addEventListener("click", function () {
      apply(lang === "en" ? "es" : "en");
    });
  });

  var menuBtn = document.getElementById("menu-btn");
  var menu = document.getElementById("menu");

  function closeMenu() {
    menu.hidden = true;
    menu.classList.remove("is-open");
    menuBtn.setAttribute("aria-expanded", "false");
    menuBtn.textContent = STR[lang].menu;
  }

  menuBtn.addEventListener("click", function () {
    var open = menu.hidden;
    menu.hidden = !open;
    menu.classList.toggle("is-open", open);
    menuBtn.setAttribute("aria-expanded", open ? "true" : "false");
    menuBtn.textContent = open ? STR[lang].close : STR[lang].menu;
  });

  menu.querySelectorAll("a").forEach(function (link) {
    link.addEventListener("click", closeMenu);
  });

  document.addEventListener("keydown", function (event) {
    if (event.key === "Escape") closeMenu();
  });
